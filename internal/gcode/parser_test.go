func TestParsePrusaSlicer(t *testing.T) {
	input := `; generated by PrusaSlicer 2.7.1
; filament used [mm] = 4500.50
; filament used [g] = 13.42
; estimated printing time (normal mode) = 1h 30m 5s
; nozzle_temperature = 215
; bed_temperature = 60
; layer_height = 0.2
; input_filename = benchy.stl
G28
G1 X0 Y0 Z0.2 F3000
`
	meta, err := Parse(strings.NewReader(input))
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}

	if meta.Slicer != "PrusaSlicer" {
		t.Errorf("slicer: got %q, want %q", meta.Slicer, "PrusaSlicer")
	}
	if meta.FilamentLengthMM != 4500.50 {
		t.Errorf("filament length: got %f, want %f", meta.FilamentLengthMM, 4500.50)
	}
	if meta.FilamentWeightG != 13.42 {
		t.Errorf("filament weight: got %f, want %f", meta.FilamentWeightG, 13.42)
	}
	expected := 1*time.Hour + 30*time.Minute + 5*time.Second
	if meta.PrintDuration != expected {
		t.Errorf("print duration: got %v, want %v", meta.PrintDuration, expected)
	}
	if meta.NozzleTempC != 215 {
		t.Errorf("nozzle temp: got %d, want %d", meta.NozzleTempC, 215)
	}
	if meta.BedTempC != 60 {
		t.Errorf("bed temp: got %d, want %d", meta.BedTempC, 60)
	}
	if meta.LayerHeight != 0.2 {
		t.Errorf("layer height: got %f, want %f", meta.LayerHeight, 0.2)
	}
	if meta.ModelName != "benchy" {
		t.Errorf("model name: got %q, want %q", meta.ModelName, "benchy")
	}
}

