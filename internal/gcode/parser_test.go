func TestParseDuration(t *testing.T) {
	tests := []struct {
		input string
		want  time.Duration
	}{
		{"1h 30m 5s", 1*time.Hour + 30*time.Minute + 5*time.Second},
		{"45m", 45 * time.Minute},
		{"2h", 2 * time.Hour},
		{"30s", 30 * time.Second},
		{"1d 2h 30m", 26*time.Hour + 30*time.Minute},
		{"  3h 10m  ", 3*time.Hour + 10*time.Minute},
		{"", 0},
		{"no time here", 0},
	}

	for _, tt := range tests {
		got := parseDuration(tt.input)
		if got != tt.want {
			t.Errorf("parseDuration(%q) = %v, want %v", tt.input, got, tt.want)
		}
	}
}

