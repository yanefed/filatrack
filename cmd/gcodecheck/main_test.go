func TestMainReturnsUsageExitCode(t *testing.T) {
	originalArgs, originalStdout, originalStderr, originalExit := os.Args, stdout, stderr, exitProcess
	t.Cleanup(func() {
		os.Args, stdout, stderr, exitProcess = originalArgs, originalStdout, originalStderr, originalExit
	})
	var output bytes.Buffer
	os.Args = []string{"gcodecheck"}
	stdout, stderr = &output, &output
	exitCode := 0
	exitProcess = func(code int) { exitCode = code }

	main()

	if exitCode != 1 || !strings.Contains(output.String(), "Использование") {
		t.Fatalf("main result: exit=%d output=%q", exitCode, output.String())
	}
}

func TestRunUsageAndFileError(t *testing.T) {
	var stdout, stderr bytes.Buffer
	if code := run([]string{"gcodecheck"}, &stdout, &stderr); code != 1 || !strings.Contains(stderr.String(), "Использование") {
		t.Fatalf("usage result: code=%d stderr=%q", code, stderr.String())
	}
	stderr.Reset()
	if code := run([]string{"gcodecheck", filepath.Join(t.TempDir(), "missing.gcode")}, &stdout, &stderr); code != 1 || !strings.Contains(stderr.String(), "Ошибка") {
		t.Fatalf("file error result: code=%d stderr=%q", code, stderr.String())
	}
}

func TestRunPrintsMetadataAndCalculatedWeight(t *testing.T) {
	path := filepath.Join(t.TempDir(), "part.gcode")
	fixture := strings.Join([]string{
		"; generated by PrusaSlicer",
		"; model name = cube",
		"; filament used [mm] = 1000",
		"; estimated printing time = 1h 2m 3s",
		"; nozzle_temperature = 210",
		"; bed_temperature = 60",
		"; layer_height = 0.2",
	}, "\n")
	if err := os.WriteFile(path, []byte(fixture), 0o600); err != nil {
		t.Fatalf("writing fixture: %v", err)
	}
	var stdout, stderr bytes.Buffer
	if code := run([]string{"gcodecheck", path}, &stdout, &stderr); code != 0 {
		t.Fatalf("run code = %d, stderr=%q", code, stderr.String())
	}
	output := stdout.String()
	for _, want := range []string{"PrusaSlicer", "cube", "1ч 2м 3с", "210 °C", "0.20 мм", "Расчётный вес"} {
		if !strings.Contains(output, want) {
			t.Errorf("output does not contain %q: %s", want, output)
		}
	}
}

func TestRunDoesNotCalculateKnownWeight(t *testing.T) {
	path := filepath.Join(t.TempDir(), "weighted.gcode")
	if err := os.WriteFile(path, []byte("; filament used [mm] = 1000\n; filament used [g] = 10\n"), 0o600); err != nil {
		t.Fatalf("writing fixture: %v", err)
	}
	var output bytes.Buffer
	if code := run([]string{"gcodecheck", path}, &output, &output); code != 0 {
		t.Fatalf("run code = %d", code)
	}
	if strings.Contains(output.String(), "Расчётный вес") {
		t.Fatalf("known filament weight must not be recalculated: %s", output.String())
	}
}

func TestFormattingHelpers(t *testing.T) {
	if valOrNA("") != "—" || valOrNA("value") != "value" {
		t.Fatal("valOrNA returned unexpected value")
	}
	if tempOrNA(0) != "—" || tempOrNA(215) != "215 °C" {
		t.Fatal("tempOrNA returned unexpected value")
	}
	if layerOrNA(0) != "—" || layerOrNA(0.2) != "0.20 мм" {
		t.Fatal("layerOrNA returned unexpected value")
	}
	tests := []struct {
		duration time.Duration
		want     string
	}{
		{want: "—"},
		{duration: 5 * time.Second, want: "5с"},
		{duration: 2*time.Minute + 5*time.Second, want: "2м 5с"},
		{duration: time.Hour + 2*time.Minute + 5*time.Second, want: "1ч 2м 5с"},
	}
	for _, tt := range tests {
		if got := formatDuration(tt.duration); got != tt.want {
			t.Errorf("formatDuration(%v) = %q, want %q", tt.duration, got, tt.want)
		}
	}
}
